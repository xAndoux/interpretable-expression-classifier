function test_duplicate_rejection()
config = default_config();
root = tempname();
mkdir(root);
cleanup = onCleanup(@() cleanup_directory(root)); %#ok<NASGU>
names = class_names();
[x, y] = meshgrid(linspace(-1, 1, 24));
for c = 1:7
    mkdir(fullfile(root, names{c}));
    for k = 1:5
        image = uint8(127 + 70 * sin((c + 1) * x + k) .* cos((c + 2) * y - k));
        imwrite(image, fullfile(root, names{c}, sprintf('%d.png', k)));
    end
end
% One copy in another class must be rejected before any split is attempted.
source = fullfile(root, names{1}, '1.png');
copyfile(source, fullfile(root, names{2}, 'duplicate.png'));
threw = false;
try
    load_dataset(root, config);
catch exception
    threw = strcmp(exception.identifier, 'expression:DuplicateImage');
end
assert(threw, 'Exact decoded duplicate was not rejected.');
delete(fullfile(root, names{2}, 'duplicate.png'));
dataset = load_dataset(root, config);
assert(numel(dataset.labels) == 35);
assert(numel(dataset.featureNames) == 264);
assert(~dataset.identityProvided);
% Exact duplicates cannot cross splits because loading rejects the corpus.
keys = dataset.contentKeys;
assert(numel(keys) == numel(unique(keys)));
end

function cleanup_directory(root)
if exist(root, 'dir') == 7
    if ispc
        system(sprintf('rmdir /s /q "%s"', root));
    else
        % Path is generated by tempname, never user input.
        system(sprintf('rm -rf -- "%s"', root));
    end
end
end
